for key in pairs(reaper) do _G[key] = reaper[key] end

local script_path = debug.getinfo(1, "S").source:match("@(.+[\\/])")
package.path = package.path .. ";" .. script_path .. "?.lua;" .. script_path .. "lib/?.lua;"
local say = require("ReaClassical_Announce")
local groups = require("ReaClassical_MM_Groups")

if GetExtState("ReaClassical", "MixerMode") ~= "1" then
    say("Enable Mixer Mode first")
    return
end

local count = #groups.load_groups()
groups.remove_all_groups()
if count == 0 then
    say("No groups to remove")
else
    say((count == 1 and "1 group removed" or (count .. " groups removed")))
end
